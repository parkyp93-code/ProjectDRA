def H(nm, b, svc=None, mil=None, civ=None):
    d = {"nm": nm, "b": b}
    for k, v in (("svc", svc), ("mil", mil), ("civ", civ)):
        if v: d[k] = v
    return d

def N(t, h=None, n=None, g=None, loc=None, map=None, note=None, c=None):
    d = {"t": t}
    for k, v in (("h", h), ("n", n), ("g", g), ("loc", loc), ("map", map), ("note", note), ("c", c)):
        if v: d[k] = v
    return d

