def _base(nm): return re.sub(r"\s*\(.*\)$", "", nm).strip()
def _suffix(nm):
    m = re.search(r"\(([^)]*겸[^)]*)\)$", nm); return f" ({m.group(1)})" if m else ""

def _limit(h):
    mil = (h.get("mil") or "").replace("예비역 ", "")
    if h.get("mil") and not h["mil"].startswith("예비역"):
        return MIL_LIMIT.get(mil, 60), MIL_AGE.get(mil, 45)
    civ = h.get("civ") or ""
    if civ in ("국가원수", "황족", "섭정", "총독") or not civ: return None, None
    if any(k in civ for k in CAREER): return 60, 54
    return 70, 62

